/**
 * Коды выхода myc. Источник истины — docs/design/03-interfaces-and-integration.md §2.2.
 *
 * Коды никогда не переиспользуются под другое значение: на них ветвятся хуки,
 * скрипты и агенты. 10–63 зарезервированы, 64+ не используем (sysexits агентам
 * не знакомы).
 */
export enum ExitCode {
  /** Успех, в том числе с предупреждениями, если нет --strict. */
  OK = 0,
  /** Внутренняя ошибка, БД, ввод-вывод. */
  ERR = 1,
  /** Неизвестный флаг или аргумент, неверный формат, неоднозначный ID. */
  USAGE = 2,
  /** Узел, файл или воркспейс не существует. */
  NOTFOUND = 3,
  /** Claim занят, цикл зависимостей, конфликт версии при sync. */
  CONFLICT = 4,
  /** Задача заблокирована, якорь протух, схема требует миграции. */
  PRECOND = 5,
  /** Операция выполнена, но подсистема деградировала. Только с --strict. */
  DEGRADED = 6,
  /** Воркспейс не инициализирован. */
  NOWS = 7,
  /** Отказано по ACL или токену. */
  DENIED = 8,
  /** Превышен --timeout или бюджет ретривала. */
  TIMEOUT = 9,
}

/**
 * Схема, версия 9: у узла ДВА способа быть уникальным, и выбирает его не
 * `kind`, а происхождение узла.
 *
 * ЧТО БЫЛО. Один индекс `ux_nodes_content(scope, kind, content_hash)`
 * запрещал два узла с одинаковым (kind, title, body) в пределах scope.
 * Правило написано под ПАМЯТЬ и там верно: одинаковый текст — это один и тот
 * же факт, второй экземпляр не добавляет знания.
 *
 * ГДЕ ОНО ЛОЖНО. У записи, приехавшей из чужого трекера, идентичность даёт
 * id трекера, а не текст. На настоящих данных ~/src/cherry (796 задач beads)
 * это не теория: две задачи `cherry-ys5o` (in_progress) и `cherry-xxc9`
 * (open) имеют дословно совпадающие заголовок и тело, но это РАЗНЫЕ задачи с
 * разными статусами; тройка `cherry-bkrm.1.1/.1.2/.1.3` — то же самое. Ещё
 * жёстче с заметками: 265 заметок `bd note` дают 11 групп совпадающих
 * текстов и 108 лишних узлов — фразы вроде «Agent: general-purpose»
 * повторяются у двух десятков задач, оставаясь заметкой КАЖДОЙ из них.
 * Импорт падал на первом же совпадении с
 * `UNIQUE constraint failed: nodes.scope, nodes.kind, nodes.content_hash`,
 * то есть свойство чужих данных выглядело поломкой myc.
 *
 * ЧТО СТАЛО. `attrs.external_ref` — «этот узел ЕСТЬ запись вон той системы»
 * (пишет только `myc import-beads`). Он и делит узлы на два класса:
 *
 *  - без external_ref (всё, что myc завёл сам) — идентичность по содержимому,
 *    прежний индекс дословно, плюс терм `external_ref IS NULL`;
 *  - с external_ref (ввезённое) — идентичность по ссылке на источник, новый
 *    `ux_nodes_external(scope, kind, external_ref)`.
 *
 * Второй индекс не только снимает запрет, он ДОБАВЛЯЕТ гарантию: на
 * external_ref стоит идемпотентность повторного импорта («узел с этим ref
 * уже есть — синхронизируем, а не создаём»), и до сих пор её держал только
 * прикладной код import-beads. Ошибка в нём удваивала бы граф молча.
 *
 * ПОЧЕМУ НЕ ТРОГАЕМ content_hash. Он производный: любой сайт обязан получить
 * тот же хеш из (kind, title, body) — на этом стоит сходимость реплик.
 * Подмешать в него external_ref нельзя: attrs приезжают отдельными
 * set-операциями, и до их приезда узел материализовался бы с ДРУГИМ хешем,
 * чем на исходном сайте.
 *
 * ПОЧЕМУ ВЫРАЖЕНИЕ, А НЕ ЕЩЁ ОДНА g_-КОЛОНКА. Виртуальные g_-колонки в
 * `nodes` заведены под предикаты, которые читают запросы; этот json_extract
 * не читает никто, кроме двух индексов. Колонка добавила бы поле в каждую
 * прочитанную строку ради двух определений.
 *
 * НАКАТ НА СУЩЕСТВУЮЩУЮ БАЗУ. Создание ux_nodes_external упадёт, если в базе
 * уже лежат два живых узла одного kind с одинаковым external_ref, — это и
 * есть та самая тихая порча, которую индекс отныне не пускает; чинится
 * удалением дубля. Ни одного такого узла в базах, созданных прежним
 * импортом, быть не может: он уже искал по external_ref перед созданием.
 */
const SQL = `
DROP INDEX ux_nodes_content;

CREATE UNIQUE INDEX ux_nodes_content
    ON nodes(scope, kind, content_hash)
 WHERE deleted_at IS NULL AND json_extract(attrs,'$.external_ref') IS NULL;

CREATE UNIQUE INDEX ux_nodes_external
    ON nodes(scope, kind, json_extract(attrs,'$.external_ref'))
 WHERE deleted_at IS NULL AND json_extract(attrs,'$.external_ref') IS NOT NULL
`;


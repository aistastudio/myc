/**
 * Векторная схема, версия 2: таблица float32-переранжирования (§2.4
 * docs/design/02-retrieval-and-performance.md, решение S26 ARCHITECTURE.md
 * §10). Часть того же набора, что vec-001-init.ts — своя таблица учёта
 * schema_migrations_vec, применяется только когда рантайм сообщил, что vec0
 * загружен (packages/store-sqlite/src/migrations/vec.ts). Базовая схема
 * (001-init.ts) о векторах по-прежнему не знает — S26 требует этого для
 * ЛЮБОГО векторного объекта, не только для vec0-таблиц.
 *
 * ФОРМА: обычная таблица, НЕ vec0 (§2.4 второго документа). Потребитель —
 * packages/retrieval/src/vector.ts, запрос vectorQueries.f32ByNodeIds — читает
 * её обычным `node_id IN (...)`, а не MATCH, поэтому виртуальная таблица vec0
 * здесь не нужна и не подходит (vec0 не поддерживает произвольный IN-скан по
 * PK так же дёшево, как обычный индекс).
 *
 * РАЗМЕР — ОГРАНИЧЕНИЕ, А НЕ ДЕТАЛЬ (замер координатора, приложение К
 * docs/design/01a-ddl-validation.md §К.2, на 100k векторов размерности 384):
 *
 *   int8 (nodes_vec)     39 МБ
 *   float32 (все узлы)  149 МБ   — в 3.8x дороже места
 *
 * Хранить float32 для ВСЕХ узлов расточительно и не нужно: float32 читается
 * только на ступени 2 (переранжирование), и то не для всех узлов корпуса, а
 * только для пула кандидатов после int8-KNN — packages/retrieval/src/vector.ts
 * ограничивает этот пул сверху константой MAX_CANDIDATES = 1000 (по умолчанию
 * DEFAULT_CANDIDATES = 200 на запрос).
 *
 * РЕШЕНИЕ: держать float32 ГОРЯЧИМ ПОДМНОЖЕСТВОМ с вытеснением по свежести
 * обращения (LRU), а не для всего корпуса и не по требованию без предела.
 * Колонка `accessed_at` + индекс ix_vec_f32_accessed (vec-003) дают дешёвый
 * ORDER BY accessed_at LIMIT для отсечения хвоста.
 *
 * ЧИСЛО: потолок кеша — 10 000 строк, на порядок больше MAX_CANDIDATES (1000),
 * чтобы кеш переживал пересечение кандидатных пулов нескольких запросов подряд
 * без частого вымывания, но далеко не «все узлы»:
 *
 *   10 000 × 1536 Б (384 × 4)          ≈ 15 МБ  — фиксировано, не растёт с корпусом
 *   против 149 МБ на 100k узлов (весь корпус)   — экономия ≈ 90%
 *   против ~1.49 ГБ на 1M узлов (весь корпус)   — экономия ≈ 99%
 *
 * ЗАПОЛНЕНИЕ: той же очередью `jobs`, что и int8 (kind='embed') — НЕ отдельным
 * механизмом. Промах кеша на ступени 2 (узел из пула кандидатов, для которого
 * в vec_nodes_f32 ещё нет строки) ставит обычный 'embed'-джоб на досчёт
 * float32 для этого узла; тот же обработчик, отработав джоб, обновляет
 * accessed_at и, если строк стало больше потолка, удаляет самые старые по
 * ix_vec_f32_accessed. Эта миграция кладёт только схему; обработчик джобов —
 * компетенция embed-пакета, не этого набора.
 *
 * ИНВАРИАНТ НАБОРА (vec.ts): ровно один оператор на миграцию — не потому что
 * bun:sqlite молча пропускает эту DDL (это баг только CREATE VIRTUAL TABLE с
 * неизвестным модулем, обычный CREATE TABLE так не ломается), а для
 * единообразия наката всего векторного набора и чтобы assertObjectsPresent
 * в ./vec.ts проверял каждую миграцию по одному чётко описанному объекту.
 */
const SQL = `-- Кеш float32-векторов для переранжирования (§2.4, S26). Обычная
-- таблица, не vec0: читается обычным IN (...), см. vectorQueries.f32ByNodeIds
-- в packages/retrieval/src/vector.ts. Горячее подмножество с LRU-вытеснением
-- по accessed_at (индекс — vec-003-rerank-f32-lru-index.ts), а не весь корпус —
-- обоснование числом в комментарии выше файла.
CREATE TABLE vec_nodes_f32 (
  node_id       TEXT    PRIMARY KEY REFERENCES nodes(id) ON DELETE CASCADE,
  embedding_f32 BLOB    NOT NULL,
  accessed_at   INTEGER NOT NULL
)`;

export const vecMigration002RerankF32: Migration = {
  version: 2,
  name: "vec_rerank_f32",
  sql: SQL,
  objects: ["vec_nodes_f32"],
};

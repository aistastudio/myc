/**
 * Схема, версия 13: две машины вправе ввезти ОДНУ запись чужого трекера, и
 * это больше не ломает синхронизацию навсегда (memory-gemeb3d8wj41).
 *
 * ЧТО БЫЛО И ПОЧЕМУ ЭТО ДЕФЕКТ. Миграция 9 дала ввезённому узлу идентичность
 * по ссылке на источник: `ux_nodes_external(scope, kind, external_ref)`.
 * Локально правило верно и остаётся. Но `myc import-beads` одной базы beads
 * на двух машинах заводит ДВА узла с разными id и одним `external_ref` — и
 * ни один из них не ошибка: каждый сайт записал то, что видел. Мерж CRDT
 * такую пару отвергнуть не может, а UNIQUE — обязан: `applyOps` падал
 * `UNIQUE constraint failed: index 'ux_nodes_external'`, откатывал ВЕСЬ
 * пакет, и каждая следующая синхронизация падала тем же исключением. Обмен
 * между машинами вставал навсегда — тот же класс, что контент-дубликат
 * (memory-0fs4rfa6xmha, S38/S40).
 *
 * ПОЧЕМУ ЗДЕСЬ НУЖНА МИГРАЦИЯ, А ТАМ НЕ ПОНАДОБИЛАСЬ. У контента ключ
 * индекса — `content_hash`, ПРОИЗВОДНАЯ колонка: её можно понизить до
 * `<канон>:<id>`, ничего не сказав оплогу и не тронув данных узла. Ключ
 * этого индекса — сам `attrs.external_ref`, РЕПЛИЦИРУЕМОЕ значение: понизить
 * его значит соврать о том, какую запись источника этот узел представляет, и
 * разослать эту ложь остальным. Значит понижать нечего — производную колонку
 * надо завести.
 *
 * ЧТО ДЕЛАЕТ `ext_dup`. Это разрешитель конфликта, а не данные: `''` —
 * «узел держит эту внешнюю ссылку», собственный id узла — «узел понижен, эту
 * же ссылку держит кто-то другой». В индекс он входит ЧЕТВЁРТОЙ колонкой, и
 * из этого следуют оба нужных свойства сразу:
 *
 *  - два узла-держателя одной ссылки по-прежнему сталкиваются (у обоих `''`),
 *    то есть локальный запрет не ослаблен ни на йоту: `createNode` и правка
 *    `attrs.external_ref` в занятую ссылку падают тем же UNIQUE;
 *  - пониженный узел уникален по построению (id уникален, и `''` не равен
 *    ни одному id), так что пакет применяется целиком, а данные обоих узлов
 *    остаются нетронутыми — `external_ref` у понижённого тот же самый.
 *
 * Кто именно держит ссылку, решает правило, одинаковое на всех репликах
 * (queries.ts, rebalanceExternal): старший по часам `set(kind)` — момент
 * создания узла, он реплицируется, — при равенстве по id. Поэтому порядок
 * прихода операций на итог не влияет.
 *
 * ПОЧЕМУ ВЫРАЖЕНИЕ `json_extract` В ИНДЕКСЕ ОСТАЛОСЬ. Оно и есть ссылка:
 * группу узлов одной ссылки читает `Q.external_group` по этому же индексу
 * (префикс scope, kind, ref), отдельный индекс под группу не нужен. Причина
 * «почему не g_-колонка» — та же, что в миграции 9: этот json_extract не
 * читает никто, кроме индекса.
 *
 * ПОЧЕМУ НЕ НЕУНИКАЛЬНЫЙ ИНДЕКС ПЛЮС ПРОВЕРКА В КОДЕ. Тогда единственным
 * стражем правила остался бы прикладной код, и любой путь записи мимо него
 * (web, будущая поверхность, ремонтный скрипт) молча удваивал бы граф —
 * ровно та тихая порча, которую миграция 9 и закрывала.
 *
 * НАКАТ НА СУЩЕСТВУЮЩУЮ БАЗУ. Колонка добавляется с DEFAULT `''`: все живые
 * узлы становятся держателями своих ссылок, и это верно по построению —
 * прежний UNIQUE не пускал в базу двух живых с одной ссылкой, так что
 * пересоздание индекса упасть не может. Заполнять нечего, разовый ремонт не
 * нужен: прежний код не оставлял после себя состояния, он откатывал пакет
 * целиком (отчёт docs/reports/REPORT-kimi-external-dup.md §4).
 *
 * СТАРЫЕ БИНАРИ ПРОДОЛЖАЮТ РАБОТАТЬ (`readableFrom: 12`). Миграция
 * совместимая и учитывается в schema_migrations_compat (migrate.ts, там же
 * — почему иначе нельзя): schema_migrations остаётся на 12, и 0.3.11–0.3.13
 * открывают поднятую базу как свою. Совместимость не объявлена, а проверена
 * по коду 0.3.13 и живыми бинарями на копии базы:
 *
 *  - старый код не называет `ext_dup`, не копирует nodes через `SELECT *` и
 *    не пишет `ON CONFLICT` по этому индексу — лишняя колонка и четвёртый
 *    столбец индекса ему не видны;
 *  - его новый узел получает `ext_dup = ''` из DEFAULT, то есть становится
 *    держателем: занятая ссылка упирается в держателя тем же UNIQUE, что и
 *    до миграции, — локальный запрет у старого бинаря прежний, а импорт
 *    чужого дубликата падает у него так же, как падал всегда;
 *  - понижённых он не создаёт и не перебалансирует. Удалив держателя, он
 *    оставляет группу без держателя; следующая правка этой группы новым
 *    бинарём её чинит (settleExternal: сначала ссылку получает старший из
 *    прежних членов группы, и только потом вошедший узел).
 *
 * Чего старый бинарь не скрывает: `myc doctor --schema` старой версии
 * покажет колонку, таблицу учёта и текст индекса как расхождение — с его
 * точки зрения так и есть, и данных это не касается.
 */
const SQL = `
ALTER TABLE nodes ADD COLUMN ext_dup TEXT NOT NULL DEFAULT '';

DROP INDEX ux_nodes_external;

CREATE UNIQUE INDEX ux_nodes_external
    ON nodes(scope, kind, json_extract(attrs,'$.external_ref'), ext_dup)
 WHERE deleted_at IS NULL AND json_extract(attrs,'$.external_ref') IS NOT NULL
`;


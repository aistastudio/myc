/**
 * Схема, версия 8: `digest_cache` — предвычисленные дайджесты с инвалидацией
 * по `oplog.seq` (решение S4, ARCHITECTURE.md; задача memory-eb91mperrr2k).
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ `myc_meta`. До этой миграции оба кеша
 * (`prime` и счётчики `ready`) лежали в generic-таблице `myc_meta` рядом с
 * `site_id`, `schema_version` и `last_seq` — под ключами вида
 * `prime_digest_v3:<scope>:<session>:<repo>`, где ВЕСЬ ключ кеша был склеен
 * в строку, а версия базы (`seq`) пряталась внутри JSON-значения. Три
 * следствия, и все три — про правильность, а не про красоту:
 *
 * 1. Сравнение seq было НЕ В SQL. Значение доставалось строкой, парсилось
 *    JSON'ом и сравнивалось в JS — то есть устаревший payload физически
 *    покидал базу и жил в памяти процесса рядом с веткой `if`. Один
 *    неверный `if` — и вчерашний дайджест отдан как свежий, молча (И2).
 *    Здесь `seq` — КОЛОНКА, сравнение стоит в `WHERE`/`CASE` того же
 *    единственного prepared statement, что читает хвост оплога, и
 *    устаревший payload не выходит из SQLite вовсе.
 *
 * 2. Ключ был склеен строкой. `scope`, профиль и вариант (сессия+репозиторий)
 *    не различимы ни запросом, ни глазом: сбросить кеш одного скоупа,
 *    посчитать записи профиля или найти протухшие было нечем, кроме
 *    `LIKE 'prime_digest_v3:%'`. Разложенные по колонкам, они дают точечный
 *    `DELETE ... WHERE scope=?` и делают наблюдаемым то, что раньше было
 *    строковым мусором в таблице метаданных.
 *
 * 3. Два кеша не были ОДНИМ механизмом. `prime` и `ready` писали свои
 *    JSON-конверты со своими полями и своим (слегка разным) порядком
 *    проверок. Стык S4 фиксирует: кеш дайджеста один, `prime` — это
 *    profile='prime'; лейны называли одну и ту же вещь двумя именами
 *    (`prime_cache` и `digest_cache`), и пока форм две, расхождение
 *    поведения ничем не ловится.
 *
 * ФОРМА КЛЮЧА: (scope, profile, variant). `scope` и `profile` — из S4.
 * `variant` — то, чем один и тот же профиль в одном скоупе ЗАКОННО
 * различается: у `prime` это сессия и репозиторий (S58/S59), у `ready` —
 * репозиторий. Без него дайджест сессии A отдавался бы сессии B при том же
 * seq оплога, то есть фильтр охвата обходился бы попаданием в кеш — не
 * промах производительности, а утечка (это уже было заложено в строковый
 * ключ; здесь оно стало колонкой, а не соглашением о склейке).
 *
 * ПОЧЕМУ НЕТ TTL И `stored_at`. У кеша поиска
 * (packages/retrieval/src/cache.ts) TTL стоит СВЕРХ seq, потому что там в ответ входит буст свежести, считаемый от
 * `now`: seq ловит записи, но не ход часов. Дайджест — чистая функция от
 * (база, scope, вариант): `scanDigest` и счётчики `readyStats` не зовут
 * часы ВООБЩЕ (ни `Date.now()`, ни сравнения с `lease_expires`; аренда
 * меняет `status`, а это запись в оплог). Значит TTL здесь не второе
 * независимое условие, а мёртвая колонка и мёртвая ветка кода: она никогда
 * не срабатывала бы первой, и её отказ был бы не виден ни одному тесту.
 * `seq` монотонен — строки из оплога не удаляются нигде в проекте, — поэтому
 * «seq совпал, а база другая» неоткуда взяться.
 *
 * WITHOUT ROWID: строка — это ключ плюс короткий JSON, доступ всегда по
 * полному первичному ключу; лишний rowid-уровень косвенности здесь только
 * платится. Так же, как `myc_meta` и `field_clock`.
 */

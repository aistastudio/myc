/**
 * Схема код-интеллекта, версия 3: реестр проиндексированных файлов репозитория
 * (§4.3 docs/design/05-code-intelligence.md, решение S52).
 *
 * Таблица — СВЕЖЕСТНОЙ ЛЕДЖЕР, а не «список файлов»: строка в `code_files`
 * появляется только после того, как воркер джобы разобрал файл и записал его
 * определения (`code_defs`, версия 4) — и в той же транзакции. Разрыв «строка
 * есть, определений нет» обязан быть невозможным: инкрементальность решает по
 * этой строке, и строка, записанная сканом раньше разбора, пережила бы смерть
 * процесса между сканом и разбором как «свежая» с устаревшими дефсами — файл
 * больше никогда не попал бы в работу (mtime уже совпадает).
 *
 * Инкрементальность — два уровня, как у якорей (`01` §7.2):
 *   1. (mtime_ms, size_bytes) — без чтения файла;
 *   2. file_hash от содержимого — подтверждает, что mtime-тач не менял код.
 * Хеш — Bun.hash (wyhash64), не криптографический: он ловит случайное
 * расхождение, а не злоумышленника, и на корпусе репозитория (~25 МБ) это
 * разница между заметной и незаметной частью бюджета индекса.
 *
 * Здесь лежат ВСЕ файлы репозитория, не только ts/tsx/js/jsx: §5 требует
 * считать долю языков по code_files («ваш репозиторий на 63 % python…»), а
 * §6.3 — сообщать {files, langs} по просмотренному. Определения при этом
 * пишутся только для L1-языков — это забота code_defs.
 *
 * path — относительный путь в POSIX-разделителях от корня репозитория:
 * строки в базе обязаны совпадать между машинами и платформами.
 */
const SQL = `CREATE TABLE code_files (
  repo_id    TEXT    NOT NULL,
  path       TEXT    NOT NULL,
  lang       TEXT    NOT NULL,              -- ts|tsx|js|jsx (L1) или расширение без точки (L0)
  mtime_ms   INTEGER NOT NULL,              -- уровень 1: сверка без чтения файла
  size_bytes INTEGER NOT NULL,              -- уровень 1: вторая половина дешёвой сверки
  file_hash  TEXT    NOT NULL,              -- уровень 2: wyhash64 содержимого, 'wy:'+hex
  indexed_at INTEGER NOT NULL,              -- когда воркер записал эту строку и дефсы
  PRIMARY KEY (repo_id, path)
) WITHOUT ROWID`;


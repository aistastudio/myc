/**
 * Схема, версия 7: индекс охвата репозитория (решение S59,
 * packages/core/src/repo.ts).
 *
 * Охват репозитория — `collector`, `messaging-server`, «общий» — живёт в
 * `attrs` узла, а не в колонке, по той же причине, что и охват сессии S58:
 * `attrs` уже едет через оплог одним JSON-значением, а новая колонка стоила
 * бы протаскивания поля через слой запросов, репликацию, импорт/экспорт и
 * каждую `set`-операцию. Цена такого хранения — `json_extract` на каждой
 * отсеиваемой строке, и вот её снимает этот индекс.
 *
 * ПОЧЕМУ ИНДЕКС ПО ВЫРАЖЕНИЮ И ПОЧЕМУ ИМЕННО ВТОРОЙ КОЛОНКОЙ. `ready`
 * обязан остаться ОДНИМ сканом частичного индекса (И1, бюджет 5 мс на 100k):
 * очередь считает score для всех кандидатов сразу и режет top-k уже после
 * сортировки, поэтому фильтр по репозиторию стоит В ИСТОЧНИКЕ, до LIMIT.
 * Отсев по `attrs` означал бы поход в строку таблицы за КАЖДОЙ отсеиваемой
 * задачей; выражение, лежащее в самом индексе сразу за `scope`, SQLite
 * подаёт из индекса и отбрасывает чужой репозиторий, не читая строку.
 *
 * Замер на 100 000 узлов (40 000 открытых задач в 16 репозиториях, свой —
 * 1/16 корпуса): по ix_nodes_ready_repo p99 ≈ 6.6 мс, по ix_nodes_ready с
 * тем же предикатом (мутация «фильтр не часть индексного скана») p99 ≈ 12 мс.
 * Числа и порог — в packages/cli/src/commands/ready.repo-latency.test.ts.
 *
 * Ключ и предикат ДОСЛОВНО повторяют ix_nodes_ready из миграции 001: тот же
 * (scope, …, priority, updated_at) и тот же частичный WHERE. Расхождение хотя
 * бы в одном терме — и планировщик уходит в скан таблицы (та же ловушка, что
 * в комментарии к ix_nodes_ready). Выражение `json_extract` обязано совпадать
 * с {@link repoExpr}/`repoPredicate` СИМВОЛ В СИМВОЛ — SQLite подставляет
 * колонку индекса вместо выражения только при точном совпадении дерева
 * выражения.
 *
 * Старый ix_nodes_ready не удаляется: он короче на колонку и остаётся дешевле
 * для вызовов без фильтра (`myc ready` из корня экосистемы — самый частый
 * случай), а `ready` выбирает индекс по наличию фильтра.
 */
const SQL = `CREATE INDEX ix_nodes_ready_repo ON nodes(
  scope,
  json_extract(attrs,'$.repo'),
  priority,
  updated_at
) WHERE kind='task' AND status='open' AND open_blockers=0 AND deleted_at IS NULL`;


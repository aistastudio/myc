/**
 * ГДЕ ЛЕЖИТ ВОРКЕР РАЗБОРА — одна строка и для сборки, и для рантайма.
 *
 * Модуль отдельный и НАМЕРЕННО пустой от импортов по той же причине, что
 * `treesitter_pin.ts`: его читает `scripts/build.ts`, собирающий бинарь, и
 * тянуть за собой sqlite с web-tree-sitter он права не имеет.
 *
 * ПОЧЕМУ КОНСТАНТА, А НЕ `new URL("./code_index_worker.ts", import.meta.url)`.
 * `bun build --compile` НЕ вшивает воркеров: конструкцию `new Worker` бандлер
 * не видит, и в собранном бинаре этот URL указывает на .ts СБОРОЧНОЙ машины —
 * `import.meta.url` сохраняет исходный абсолютный путь. На машине сборки файл
 * на месте, и пул выглядит рабочим; у того, кто скачал бинарь, файла нет
 * вовсе, а если бы и был — standalone-рантайм не резолвит node_modules, и
 * воркер падает на `Cannot find package 'web-tree-sitter'` ещё до первой
 * строки тела. Замерено на этом репозитории: восемь воркеров из восьми,
 * каждый прогон, номер в сообщении плавал только потому, что до обработчика
 * доживал случайный из восьми отказов.
 *
 * Лечится тем, что воркер идёт ВТОРЫМ ВХОДОМ сборки:
 * `bun build --compile <main> <worker>` кладёт в bunfs его самодостаточный
 * бандл (web-tree-sitter внутри), и `new Worker` находит его там же.
 *
 * ИМЯ В BUNFS ЗАДАЁТСЯ ЯВНО, а не выводится. По умолчанию `bun build` кладёт
 * вход по пути относительно ОБЩЕГО ПРЕДКА всех входов: пока входа два и они в
 * `packages/cli` и `packages/code-intel`, воркер получает имя
 * `code-intel/src/code_index_worker.js` — то есть имя зависит от того, где
 * лежит ЧУЖОЙ вход. Третий вход или переезд main сдвинули бы его молча, и пул
 * перестал бы заводиться без единого сообщения (проверено: `entry` стал null,
 * разбор ушёл в один поток, команда отрапортовала успех). Поэтому сборка
 * передаёт `--entry-naming "[name].[ext]"`, и имя здесь — просто имя файла.
 */

/** Вход воркера относительно корня репозитория — аргумент `bun build`. */
export const PARSE_WORKER_SOURCE = "packages/code-intel/src/code_index_worker.ts";

/** Схема имён входов, которую сборка обязана передать `bun build`. */
export const PARSE_WORKER_ENTRY_NAMING = "[name].[ext]";

/** Он же внутри собранного бинаря — по схеме выше. */
export const PARSE_WORKER_IN_BINARY = `/$bunfs/root/${PARSE_WORKER_SOURCE.split("/").pop()!.replace(/\.ts$/, ".js")}`;

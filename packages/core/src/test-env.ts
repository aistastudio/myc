/**
 * Окружение для тестов, которые спавнят НАСТОЯЩИЙ процесс myc.
 *
 * Зачем это здесь, а не в каждом тесте своим списком.
 *
 * Фоновые механизмы (демон эмбеддера, разбор хвоста очереди) выключают себя
 * под тестом проверкой `NODE_ENV === "test"`. Проверка читает окружение
 * ДОЧЕРНЕГО процесса, а тесты, спавнящие CLI, собирают его белым списком —
 * PATH, HOME, TMPDIR и пара своих переменных. `NODE_ENV` в такой список не
 * попадает, и защита не срабатывает.
 *
 * Это ловушка S51, и она уже сработала ДВАЖДЫ. Первый раз демон эмбеддера
 * переживал свой воркспейс и досиживал десятиминутный TTL с базой в удалённом
 * каталоге. Второй раз разбор очереди съедал absorb-работу внутри `myc
 * remember`, и приёмка И2 находила пустую очередь вместо деградации — причём
 * комментарий о первой ловушке стоял строкой выше того места, куда надо было
 * дописать вторую переменную.
 *
 * Значит дело не в забывчивости. Схема «каждый механизм заводит свой
 * выключатель, каждый спавнящий тест обязан помнить их все» ломается на каждом
 * новом механизме, а цена растёт как произведение механизмов на тесты. Реестр
 * ниже плюс тест на исчерпывающность (core/test-env.test.ts) закрывают это так
 * же, как `STORE_PRAGMAS` закрыл расползание PRAGMA по трём путям открытия базы
 * (решение S43): новый механизм добавляет строку В ОДНО место, иначе набор
 * краснеет.
 */

/**
 * Переменные, гасящие фоновые механизмы в дочернем процессе myc.
 *
 * ДОБАВЛЯЯ НОВЫЙ ФОНОВЫЙ МЕХАНИЗМ, впиши его выключатель сюда. Тест на
 * исчерпывающность найдёт функцию, которая читает `NODE_ENV === "test"` вместе
 * со своей `MYC_*`, и покраснеет, если её здесь нет.
 */
export const BACKGROUND_SWITCHES: readonly string[] = [
  "MYC_DRAIN",
  // Фоновый прогон лестницы якорей (§7.5) внутри дренажа. Выключатель свой, а
  // не общий с MYC_DRAIN, потому что этот механизм читает ФАЙЛЫ РЕПОЗИТОРИЯ:
  // тест, правящий файлы под собой, обязан уметь погасить именно его.
  "MYC_ANCHOR_CHECK",
  // Фоновый вход код-индекса (§4.3): шаг дренажа ПОДНИМАЕТ отсоединённый
  // процесс `myc code index`, который ходит по всему дереву репозитория.
  // Тесту, правящему файлы под собой, нужно уметь погасить именно его.
  "MYC_CODE_INDEX",
  "MYC_EMBED_DAEMON",
  // Проверка обновлений: единственный механизм, который ходит в СЕТЬ.
  // Выключен по умолчанию (режим `manual`), но спавнящий тест обязан гасить
  // его явно — иначе `MYC_UPDATE_CHECK=1` из окружения разработчика поднял бы
  // отсоединённый процесс с сетью посреди теста.
  "MYC_UPDATE_CHECK",
];

/**
 * Белый список окружения для спавна myc в тестах: минимум системных переменных
 * плюс все выключатели фона. `extra` добавляется поверх и может переопределить
 * что угодно — тесту самого механизма нужно уметь его ВКЛЮЧИТЬ.
 */
export function cliTestEnv(extra: Readonly<Record<string, string>> = {}): Record<string, string> {
  const base: Record<string, string> = {
    PATH: process.env.PATH ?? "",
    HOME: process.env.HOME ?? "",
    TMPDIR: process.env.TMPDIR ?? "/tmp",
    NO_COLOR: "1",
  };
  for (const name of BACKGROUND_SWITCHES) base[name] = "0";
  return { ...base, ...extra };
}

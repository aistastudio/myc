-- Роль, которой сервер ходит в базу. Создаётся ДО схемы и один раз, при
-- инициализации кластера (docker-entrypoint-initdb.d).
--
-- Почему не в db/schema.postgres.sql: схема создаёт myc_app как NOLOGIN без
-- пароля и выдаёт ей права — пароль в версионируемом файле означал бы один
-- пароль у всех установок. Схема делает CREATE ROLE только «если нет», так
-- что эта роль со входом её переживает: она найдёт готовую и просто выдаст
-- права.
--
-- Пароль здесь образцовый. В настоящей установке его берут из секрета
-- оркестратора — и тем же значением правят MYC_PG_URL в compose.yml.
CREATE ROLE myc_app LOGIN PASSWORD 'change-me';
